#!/usr/bin/env bash
set -Eeuo pipefail

###############################################################################
# Portal Update 007
#
# Unified initial administrator setup for the NetFortress deployment.
#
# Brings a portal at update level 6 to level 7:
#
#   - The initial setup page configures ONE administrator account
#     for BOTH the Portal and the local NetFortress appliance
#     (deployment option 2).
#   - /initial-setup is provider aware: option 1 keeps the existing
#     Technitium flow unchanged.
#   - New /initial-setup-info endpoint tells the setup page which
#     deployment shape it is serving.
#   - setup.php hides the current-password step and enforces the
#     appliance password policy (12+ characters) on option 2.
#
# The api/config.py file and web uploads are preserved.
###############################################################################

UPDATE_NAME="Update 007 - Unified Initial Administrator Setup"

API_DIR="/opt/portal/api"
WEB_DIR="/opt/portal/web"
PORTAL_DIR="/opt/portal"
CONFIG_FILE="$API_DIR/config.py"
VERSION_FILE="/var/lib/portal/update-version"
BACKUP_ROOT="/var/backups/portal"
CODE_BACKUP_DONE=0

log() { printf '\n======================================================================\n%s\n======================================================================\n' "$1"; }
ok() { echo "[ OK ] $1"; }
warn() { echo "[WARN] $1"; }
fail() { echo "[ERROR] $1" >&2; return 1; }

on_error() {
    local rc=$?
    trap - ERR EXIT
    if [[ $rc -ne 0 ]]; then
        echo ""
        echo "[WARN] Update 007 failed (rc=$rc); starting rollback"
        if [[ "$CODE_BACKUP_DONE" -eq 1 && -f "$BACKUP_DIR/code-before.tar.gz" ]]; then
            tar -xzf "$BACKUP_DIR/code-before.tar.gz" -C / || warn "code restore failed"
            ok "Code tree restored"
        fi
        systemctl restart portal-api.service >/dev/null 2>&1 || true
        echo "[ERROR] Update 007 aborted"
    fi
    exit $rc
}

trap on_error EXIT

log "$UPDATE_NAME"

[[ $EUID -eq 0 ]] || fail "This update must be run as root"

for cmd in base64 python3 systemctl tar curl; do
    command -v "$cmd" >/dev/null 2>&1 || fail "Required command not found: $cmd"
done

[[ -f "$API_DIR/main.py" ]] || fail "File not found: $API_DIR/main.py"
[[ -f "$WEB_DIR/setup.php" ]] || fail "File not found: $WEB_DIR/setup.php"
[[ -f "$VERSION_FILE" ]] || fail "Update state file not found: $VERSION_FILE"

CURRENT_UPDATE="$(tr -d '[:space:]' < "$VERSION_FILE")"

if [[ ! "$CURRENT_UPDATE" =~ ^[0-9]+$ ]]; then
    fail "Invalid installed update level: $CURRENT_UPDATE"
fi

if (( CURRENT_UPDATE >= 7 )); then
    ok "Update 007 is already applied (level $CURRENT_UPDATE)"
    exit 0
fi

if (( CURRENT_UPDATE < 6 )); then
    fail "This update requires update level 6 (found $CURRENT_UPDATE). Apply the earlier updates first."
fi

ok "Installed update level: $CURRENT_UPDATE"

log "VALIDATING CURRENT FILES"

MAIN_TEXT="$(cat "$API_DIR/main.py")"

if ! grep -q 'class InitialSetupRequest' <<<"$MAIN_TEXT"; then
    fail "main.py does not match the level-6 release (initial setup endpoint missing)."
fi

if grep -q '_initial_setup_firewall' <<<"$MAIN_TEXT"; then
    fail "main.py already contains the unified setup; this is not a level-6 main.py"
fi

ok "main.py source validated (level-6 initial setup present)"

STAGE_DIR="$(mktemp -d /tmp/portal-update007.XXXXXX)"
BACKUP_DIR="$BACKUP_ROOT/update007-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP_DIR"

log "BACKING UP CURRENT STATE"

tar -czf "$BACKUP_DIR/code-before.tar.gz" -C / opt/portal/api/main.py opt/portal/web/setup.php 2>/dev/null || fail "code backup failed"
CODE_BACKUP_DONE=1
ok "Code tree backed up"

log "STAGING UPDATE 007 PAYLOAD"

