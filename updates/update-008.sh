#!/usr/bin/env bash
set -Eeuo pipefail

###############################################################################
# Portal Update 008
#
# Provider token re-mint at setup completion.
#
# The installer mints the portal provider API token under the temporary
# appliance setup account (portal-setup). That account is disabled when
# the setup page completes, and the appliance refuses API tokens that
# belong to disabled users - which invalidated the portal provider
# token on every fresh option 2 deployment (block, unblock and user
# sync all failed with 401).
#
# This update re-mints the provider token under the real administrator
# during setup, before the temporary account is disabled, and applies
# the new token to both config.py and the running provider module.
###############################################################################

UPDATE_NAME="Update 008 - Provider Token Re-Mint at Setup Completion"

API_DIR="/opt/portal/api"
PORTAL_DIR="/opt/portal"
VERSION_FILE="/var/lib/portal/update-version"
BACKUP_ROOT="/var/backups/portal"
CODE_BACKUP_DONE=0

log() { printf '\n======================================================================\n%s\n======================================================================\n' "$1"; }
ok() { echo "[ OK ] $1"; }
warn() { echo "[WARN] $1"; }
fail() { echo "[ERROR] $1" >&2; return 1; }

on_error() {
    local rc=$?
    trap - ERR EXIT
    if [[ $rc -ne 0 ]]; then
        echo ""
        echo "[WARN] Update 008 failed (rc=$rc); starting rollback"
        if [[ "$CODE_BACKUP_DONE" -eq 1 && -f "$BACKUP_DIR/code-before.tar.gz" ]]; then
            tar -xzf "$BACKUP_DIR/code-before.tar.gz" -C / || warn "code restore failed"
            ok "Code tree restored"
        fi
        systemctl restart portal-api.service >/dev/null 2>&1 || true
        echo "[ERROR] Update 008 aborted"
    fi
    exit $rc
}

trap on_error EXIT

log "$UPDATE_NAME"

[[ $EUID -eq 0 ]] || fail "This update must be run as root"

for cmd in base64 python3 systemctl tar curl; do
    command -v "$cmd" >/dev/null 2>&1 || fail "Required command not found: $cmd"
done

[[ -f "$API_DIR/main.py" ]] || fail "File not found: $API_DIR/main.py"
[[ -f "$VERSION_FILE" ]] || fail "Update state file not found: $VERSION_FILE"

CURRENT_UPDATE="$(tr -d '[:space:]' < "$VERSION_FILE")"

if [[ ! "$CURRENT_UPDATE" =~ ^[0-9]+$ ]]; then
    fail "Invalid installed update level: $CURRENT_UPDATE"
fi

if (( CURRENT_UPDATE >= 8 )); then
    ok "Update 008 is already applied (level $CURRENT_UPDATE)"
    exit 0
fi

if (( CURRENT_UPDATE < 7 )); then
    fail "This update requires update level 7 (found $CURRENT_UPDATE). Apply the earlier updates first."
fi

ok "Installed update level: $CURRENT_UPDATE"

log "VALIDATING CURRENT FILES"

MAIN_TEXT="$(cat "$API_DIR/main.py")"

if ! grep -q '_initial_setup_firewall' <<<"$MAIN_TEXT"; then
    fail "main.py does not match the level-7 release (unified setup endpoint missing)."
fi

if grep -q '_switch_provider_token' <<<"$MAIN_TEXT"; then
    fail "main.py already contains the token re-mint; this is not a level-7 main.py"
fi

ok "main.py source validated (level-7 unified setup present)"

STAGE_DIR="$(mktemp -d /tmp/portal-update008.XXXXXX)"
BACKUP_DIR="$BACKUP_ROOT/update008-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP_DIR"

log "BACKING UP CURRENT STATE"

tar -czf "$BACKUP_DIR/code-before.tar.gz" -C / opt/portal/api/main.py 2>/dev/null || fail "code backup failed"
CODE_BACKUP_DONE=1
ok "Code tree backed up"

log "STAGING UPDATE 008 PAYLOAD"

